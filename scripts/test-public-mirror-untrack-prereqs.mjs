#!/usr/bin/env node
/**
 * test-public-mirror-untrack-prereqs.mjs — deterministic live re-measurement
 * of the #377 public-mirror untracking prerequisites.
 *
 * The dated snapshot ("18 staging workflows / 54 true orphans / 1,025
 * regenerable shard assets", 2026-08-03) is intentionally NOT trusted: every
 * number below is re-measured from the live tree on each run. Tree-state
 * only (no network, no writes except the disposition snapshot at
 * scripts/public-mirror-untrack-disposition.json).
 *
 * Measurements:
 *   staging_workflows — every workflow whose shell names a
 *     100xfenok-next/public/data path in a `git add`, after line-continuation
 *     normalization, excluding the merge-boundary workflows that legitimately
 *     own the mirror (update-manifest.yml, fetch-stockanalysis.yml). Anything
 *     else is lane-owned staging and blocks untracking.
 *   mirror orphans — mirror files with no canonical counterpart in data/,
 *     classified deterministically as:
 *       boundary-copy            canonical data/<rel> exists; the sync full
 *                                walk copies it, so it is not an orphan.
 *       generated                no canonical; produced by the sync transform
 *                                roots (computed/market_facts/shards/,
 *                                stockanalysis/etfs/shards/) or another
 *                                boundary regenerator; regenerable, never
 *                                committed as source.
 *       private-preserve         no canonical; under a private excluded
 *                                root/file or a forbidden mirror pattern —
 *                                must never be public; keep out of any
 *                                deletion/untrack plan.
 *       archive-preserve         no canonical; under a documented legacy
 *                                archive root (currently none — winddown and
 *                                friends are boundary copies).
 *       genuine-delete-candidate everything else: leftover from pre-boundary
 *                                lane staging; safe to plan removal/untrack.
 *
 * Untrack-ready invariants asserted (exit 1 on violation, disposition still
 * written so the failure is reviewable):
 *   A. lane-owned staging workflows == 0
 *   B. private-preserve mirror files == 0
 *   C. genuine-delete-candidate + archive-preserve mirror files == 0
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  EXCLUDED_PUBLIC_DATA_FILES,
  EXCLUDED_PUBLIC_DATA_ROOTS,
} from "../100xfenok-next/scripts/sync-public-data.mjs";
import {
  FORBIDDEN_PATTERNS,
  FORBIDDEN_PRIVATE_DATA_SUPPLY_ROOTS,
} from "../100xfenok-next/scripts/check-fenok-public-mirror-guard.mjs";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "..");
const WORKFLOWS_DIR = path.join(REPO_ROOT, ".github", "workflows");
const CANONICAL_ROOT = path.join(REPO_ROOT, "data");
const MIRROR_ROOT = path.join(REPO_ROOT, "100xfenok-next", "public", "data");
const DISPOSITION_PATH = path.join(SCRIPT_DIR, "public-mirror-untrack-disposition.json");

// The merge boundary workflows that legitimately write the mirror.
const BOUNDARY_WORKFLOWS = new Set([
  ".github/workflows/update-manifest.yml",
  ".github/workflows/fetch-stockanalysis.yml", // full sync + its commit
]);

// Sync transform roots: files under these have no canonical counterpart by
// design and are regenerated by sync-public-data.mjs on every boundary run.
const GENERATED_ROOTS = Object.freeze([
  "computed/market_facts/shards/",
  "stockanalysis/etfs/shards/",
]);

// Documented legacy archive roots whose mirror copies have no canonical
// counterpart and must be preserved, not deleted. None exist today; winddown
// and the other legacy families are boundary copies of canonical data.
const ARCHIVE_PRESERVE_ROOTS = Object.freeze([]);

function walkFiles(dir, relativeBase, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walkFiles(absolute, relativeBase, out);
    } else if (entry.isFile()) {
      out.push(path.relative(relativeBase, absolute).split(path.sep).join("/"));
    }
  }
  return out;
}

function isCoveredByRoot(relativePath, root) {
  return relativePath === root || relativePath.startsWith(root);
}

function classifyMirrorFile(relativePath) {
  if (fs.existsSync(path.join(CANONICAL_ROOT, relativePath))) {
    return "boundary-copy";
  }
  if (GENERATED_ROOTS.some((root) => isCoveredByRoot(relativePath, root))) {
    return "generated";
  }
  if (ARCHIVE_PRESERVE_ROOTS.some((root) => isCoveredByRoot(relativePath, root))) {
    return "archive-preserve";
  }
  const privateRootMatch = EXCLUDED_PUBLIC_DATA_ROOTS.some((root) => isCoveredByRoot(relativePath, root));
  const privateFileMatch = EXCLUDED_PUBLIC_DATA_FILES.includes(relativePath);
  const forbiddenPatternMatch = [
    ...FORBIDDEN_PATTERNS,
    ...FORBIDDEN_PRIVATE_DATA_SUPPLY_ROOTS.map((root) => new RegExp(`^${root.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(/|$)`)),
  ].some((pattern) => pattern.test(relativePath));
  if (privateRootMatch || privateFileMatch || forbiddenPatternMatch) {
    return "private-preserve";
  }
  return "genuine-delete-candidate";
}

export function measureStagingWorkflows({ workflowsDir = WORKFLOWS_DIR } = {}) {
  const laneOwned = [];
  const boundaryOwned = [];
  for (const entry of fs.readdirSync(workflowsDir, { withFileTypes: true })) {
    if (!entry.name.endsWith(".yml")) continue;
    const rel = `.github/workflows/${entry.name}`;
    const source = fs.readFileSync(path.join(workflowsDir, entry.name), "utf8");
    // Normalize shell line continuations so a `git add -- \` split across two
    // lines cannot hide a mirror path from the scan.
    const normalized = source.replace(/\\[ \t]*\r?\n[ \t]*/g, " ");
    const lines = normalized.split("\n").filter((line) =>
      /git\s+add.*?100xfenok-next\/public\/data(?:\/|$)/.test(line));
    if (lines.length === 0) continue;
    const target = BOUNDARY_WORKFLOWS.has(rel) ? boundaryOwned : laneOwned;
    for (const line of lines) target.push(`${rel}: ${line.trim()}`);
  }
  laneOwned.sort();
  boundaryOwned.sort();
  return { laneOwned, boundaryOwned };
}

export function measureMirrorDisposition({ mirrorRoot = MIRROR_ROOT } = {}) {
  const disposition = {
    "boundary-copy": [],
    generated: [],
    "private-preserve": [],
    "archive-preserve": [],
    "genuine-delete-candidate": [],
  };
  for (const relativePath of walkFiles(mirrorRoot, mirrorRoot).sort()) {
    disposition[classifyMirrorFile(relativePath)].push(relativePath);
  }
  return disposition;
}

function main() {
  const staging = measureStagingWorkflows();
  const disposition = measureMirrorDisposition();
  const counts = Object.fromEntries(
    Object.entries(disposition).map(([className, files]) => [className, files.length]),
  );

  const snapshot = {
    schema_version: "public-mirror-untrack-disposition/v1",
    measured_at: new Date().toISOString(),
    method:
      "live tree scan; boundary-copy = canonical counterpart exists; generated = sync transform root; " +
      "private-preserve = excluded/forbidden; archive-preserve = legacy archive root; " +
      "genuine-delete-candidate = remainder",
    staging_workflows: {
      lane_owned_count: staging.laneOwned.length,
      lane_owned: staging.laneOwned,
      boundary_owned: staging.boundaryOwned,
    },
    mirror_counts: {
      total_files: Object.values(counts).reduce((sum, count) => sum + count, 0),
      ...counts,
    },
    // Boundary copies are provably covered by the sync (canonical existence is
    // the classification itself); keep the snapshot compact with a
    // deterministic sample. Orphan-relevant classes are listed in full.
    disposition: {
      ...Object.fromEntries(
        ["generated", "private-preserve", "archive-preserve", "genuine-delete-candidate"]
          .map((className) => [className, disposition[className]]),
      ),
      "boundary-copy_sample": [
        ...disposition["boundary-copy"].slice(0, 10),
        ...(disposition["boundary-copy"].length > 20
          ? disposition["boundary-copy"].slice(-10)
          : disposition["boundary-copy"].slice(10)),
      ],
    },
  };
  fs.writeFileSync(DISPOSITION_PATH, `${JSON.stringify(snapshot, null, 2)}\n`);

  console.log(
    `public-mirror untrack prerequisites:\n` +
      `  staging workflows: lane_owned=${staging.laneOwned.length} boundary_owned=${staging.boundaryOwned.length}\n` +
      `  mirror files: total=${snapshot.mirror_counts.total_files} ` +
      `boundary_copy=${counts["boundary-copy"]} generated=${counts.generated} ` +
      `private_preserve=${counts["private-preserve"]} archive_preserve=${counts["archive-preserve"]} ` +
      `genuine_delete_candidate=${counts["genuine-delete-candidate"]}\n` +
      `  disposition snapshot: ${path.relative(REPO_ROOT, DISPOSITION_PATH)}`,
  );

  const violations = [];
  if (staging.laneOwned.length > 0) {
    violations.push(`lane-owned mirror staging (${staging.laneOwned.length}):\n- ${staging.laneOwned.join("\n- ")}`);
  }
  if (counts["private-preserve"] > 0) {
    violations.push(`private-preserve mirror files (${counts["private-preserve"]}) — a private root is public:\n- ${disposition["private-preserve"].join("\n- ")}`);
  }
  const deleteCandidates = counts["genuine-delete-candidate"] + counts["archive-preserve"];
  if (deleteCandidates > 0) {
    violations.push(`true mirror orphans (${deleteCandidates}):\n- ${[...disposition["genuine-delete-candidate"], ...disposition["archive-preserve"]].join("\n- ")}`);
  }
  if (violations.length) {
    console.error(`\nUNTRACK PREREQUISITES NOT MET (${violations.length}):`);
    for (const violation of violations) console.error(`- ${violation}`);
    process.exit(1);
  }
  console.log("\nuntrack-ready: no lane-owned mirror staging; no private leaks; no true orphans");
}

main();
